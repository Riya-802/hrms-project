/**
 * Returns formatted localized current date (e.g., Sat, Sep 12, 2026)
 */
export const getFormattedCurrentDate = (langCode = 'EN') => {
  const localeMap = {
    EN: 'en-US',
    ES: 'es-ES',
    FR: 'fr-FR',
    DE: 'de-DE',
    HI: 'hi-IN'
  };
  const locale = localeMap[langCode] || 'en-US';

  const now = new Date();
  return now.toLocaleDateString(locale, {
    weekday: 'short',
    month: 'short',
    day: 'numeric',
    year: 'numeric'
  });
};
